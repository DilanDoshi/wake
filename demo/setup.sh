#!/usr/bin/env bash
# Builds the recording workspace: the Harbor checkout, the PATH shim that puts
# the scripted agent where Wake looks for `claude`, and a scratch socket.
#
# Everything it makes lives under demo/.work, which is ignored. Re-runnable.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/.." && pwd)"
work="$here/.work"
# Inside the scratch HOME, so every path on camera is drawn as ~/harbor/… — a
# path outside it is drawn whole, and that put the operator's name in the frame.
harbor="$work/claudehome/harbor"
# `wake status` prints the socket whole, so it lives at a path that names no one.
# A shell that sources env.sh by hand gets this one; every take mints its own.
sock=/tmp/wake-demo/wake.sock

# Takes are expensive — a full set is ~25 minutes of recording — so re-running
# setup must never destroy them. Everything below is rebuilt; out/ and cards/
# are left exactly where they are.
rm -rf "$work/bin" "$work/harbor" "$work/claudehome" "$work/seg"
mkdir -p "$work/bin" "$work/out" "$work/cards" "$(dirname "$sock")"

# The fictional product, as a real git repository — the conversation status bar
# reads a real branch through internal/gitref, so a drawn one would be a lie on
# camera.
mkdir -p "$work/claudehome"
cp -R "$here/harbor" "$harbor"
git -C "$harbor" init --quiet --initial-branch=main
git -C "$harbor" -c user.email=dev@harbor.dev -c user.name=Harbor \
    add -A
git -C "$harbor" -c user.email=dev@harbor.dev -c user.name=Harbor \
    commit --quiet -m "harbor 0.4.0"
git -C "$harbor" checkout --quiet -b feat/rate-limit

# What Wake spawns. internal/core resolves `claude` on PATH and nothing else,
# so a shim directory in front of PATH is the whole substitution.
ln -sf "$here/agent/claude" "$work/bin/claude"

# The real binary, built from this worktree.
# No VCS stamp: a worktree build reports "-dirty" in `wake status`, on camera.
( cd "$root" && go build -buildvcs=false -o "$work/bin/wake" ./cmd/wake )

# A scratch HOME for the whole recording. Wake reads conversations back from
# $HOME/.claude/projects, so this both gives the fake somewhere to journal and
# guarantees nothing of the operator's real Claude data can reach the camera.
#
# Named `claudehome` rather than `home` because internal/core's corpus guard
# matches a unix home path with an owner attached, tree-wide, to catch a leaked
# home directory — and the shorter name trips it on the `.claude` beneath.
mkdir -p "$work/claudehome/.claude/projects/harbor"

# POSIX: zsh sources it in a tape, bash in record.sh. The terminal's variables go
# (cmux's would draw the friend as a Kitty image VHS cannot show), and wake runs
# under shiftkeys.py - whichever wake PATH names, so WF_BIN still wins.
cat > "$work/env.sh" <<EOF
# source this to record
export PATH="$work/bin:\$PATH"
export HOME="$work/claudehome"
export WAKE_SOCKET="$sock"
export WAKE_DEMO_SCENARIOS="$here/scenarios"
export HARBOR="$harbor"
export PS1="%F{244}harbor%f %F{209}\$%f "
export WAKE_FRIEND_ART=blocks COLORTERM=truecolor WAKE_NO_UPDATE_CHECK=1
for v in \$(env | sed -n 's/^\\(CMUX[A-Za-z0-9_]*\\)=.*/\\1/p'); do unset "\$v"; done
unset TERM_PROGRAM TERM_PROGRAM_VERSION GHOSTTY_RESOURCES_DIR GHOSTTY_SURFACE_ID GHOSTTY_BIN GHOSTTY_SHELL_FEATURES KITTY_WINDOW_ID WEZTERM_PANE TMUX STY
wake() { "$here/shiftkeys.py" wake "\$@"; }
EOF

# The staging tape is generated rather than written, because `/new <name> in
# <dir>` resolves a relative directory against the *session's* directory, not
# the shell's — so `in web` from an agent started in api/ means api/web, which
# does not exist, and a refused command keeps its draft for the next line to
# concatenate onto. Absolute paths remove the question.
cat > "$work/stage.tape" <<EOF
# GENERATED by demo/setup.sh — edit setup.sh, not this file.
#
# The fleet every beat is filmed against. Sourced, never recorded: each beat
# tape wraps it in Hide and calls Show once the room is ready.
#
# \`wake new maya\` rather than a bare \`wake\`, because a bare one starts the
# manager and no agent, and the cast needs maya by name.

Set TypingSpeed 8ms

# A socket and a friend pick per take, the socket in .work/take-socket for
# record.sh to end; its directory names the manager, manager-harbor.
Type "source ./.work/env.sh && take=\$(mktemp -d /tmp/wake-take.XXXXXX) && mkdir \$take/harbor && export WAKE_SOCKET=\$take/harbor/wake.sock WAKE_FRIENDS_FILE=\$take/friends.json && echo \$WAKE_SOCKET > ./.work/take-socket && cd \$HARBOR/api && clear || exit 1"
Enter
Sleep 2s

Type "wake new maya"
Enter
Sleep 7s

# Close maya's pane, so staging happens against the room alone.
Ctrl+W
Sleep 2s

# \`/new\` drafts \`@<name> \` into the room composer once the spawn lands, so the
# operator can address the new agent at once. Here the next line would
# concatenate onto that mention, so each one is cleared with \`⎋\` — which in
# the room clears the draft and nothing else.
Type "/new omar in $harbor/web"
Enter
Sleep 6s
Escape
Sleep 500ms
Type "/new priya in $harbor/cli"
Enter
Sleep 6s
Escape
Sleep 500ms
Type "/new luca in $harbor/docs"
Enter
Sleep 6s
Escape
Sleep 500ms
Type "/new nora in $harbor/api"
Enter
Sleep 6s
Escape
Sleep 500ms
Type "/new alex in $harbor/api"
Enter
Sleep 6s

# The last \`/new\` drafted its mention too. Clear it before the labels go in.
Escape
Sleep 1s

# Labels are what a fleet is triaged by: they head every line an agent says,
# fill the roster and the board, and are the only handle the manager has for
# "the agents working on the api".
Type "/task @maya api · token-bucket middleware"
Enter
Sleep 3s
Type "/task @omar web · 429 client state"
Enter
Sleep 3s
Type "/task @priya cli · --rate-limit flag"
Enter
Sleep 3s
Type "/task @luca docs · changelog and limits page"
Enter
Sleep 3s
Type "/task @nora api · limiter tests"
Enter
Sleep 3s
Type "/task @alex api · limiter benchmarks"
Enter
Sleep 4s

Set TypingSpeed 55ms
EOF

# Recording settings shared by every beat tape. Generated here so a re-run of
# setup cannot leave the tapes pointing at a file that no longer exists.
# 4/3 of the old 2400x1320 at 16: the same columns, sharper. Larger drops frames
# under load and the take plays fast - check a take's length against its script.
cat > "$work/head.tape" <<'EOT'
# GENERATED by demo/setup.sh — edit setup.sh, not this file.
Set Shell zsh
Set FontSize 21
Set Width 3200
Set Height 1760
Set Padding 32
Set Framerate 25
Set WindowBar Colorful
EOT

echo "workspace ready: $work"
echo "  harbor  $(git -C "$harbor" branch --show-current)"
echo "  claude  $(readlink "$work/bin/claude")"
echo "  wake    $("$work/bin/wake" --version 2>/dev/null || echo built)"
